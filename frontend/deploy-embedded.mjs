#!/usr/bin/env node
// Fallback deployer for a portal: packs frontend/<app>/build into ONE Worker script
// (files embedded, SPA fallback, cache + security headers) and deploys it WITHOUT the
// Workers static-assets upload API.
//
// Normal path is `npm run deploy` (Workers static assets) / GitHub Actions. Use this only
// where the assets upload endpoint is unreachable (e.g. a proxy that rewrites the upload
// token). Same Worker names, so a later normal deploy simply replaces it.
//
//   node deploy-embedded.mjs doer|admin [--dry-run]
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";

const app = process.argv[2];
const NAMES = { doer: "epil-portal", admin: "epil-admin" };
if (!NAMES[app]) { console.error("usage: node deploy-embedded.mjs doer|admin [--dry-run]"); process.exit(1); }
const here = import.meta.dirname;
const build = path.join(here, app, "build");
const TYPES = {
  ".html": "text/html; charset=utf-8", ".js": "application/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8", ".txt": "text/plain; charset=utf-8", ".svg": "image/svg+xml",
  ".png": "image/png", ".ico": "image/x-icon", ".jpg": "image/jpeg", ".webp": "image/webp", ".woff2": "font/woff2", ".map": "application/json",
};
const TEXT = new Set([".html", ".js", ".css", ".json", ".txt", ".svg", ".map"]);

const files = {};
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = path.join(dir, f);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const rel = "/" + path.relative(build, p).split(path.sep).join("/");
    if (rel === "/_headers" || rel.endsWith(".map")) continue;
    const ext = path.extname(p).toLowerCase();
    files[rel] = TEXT.has(ext)
      ? { t: TYPES[ext] || "text/plain", s: readFileSync(p, "utf8") }
      : { t: TYPES[ext] || "application/octet-stream", b: readFileSync(p).toString("base64") };
  }
})(build);
if (!files["/index.html"]) { console.error(`No build found in ${build} — run npm run build first`); process.exit(1); }

const worker = `// Generated by frontend/deploy-embedded.mjs — do not edit.
const FILES = ${JSON.stringify(files)};
const SECURITY = {
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "DENY",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
  "Strict-Transport-Security": "max-age=15552000; includeSubDomains",
};
const decoded = new Map();
function body(path, f) {
  if (f.s !== undefined) return f.s;
  if (!decoded.has(path)) decoded.set(path, Uint8Array.from(atob(f.b), (c) => c.charCodeAt(0)));
  return decoded.get(path);
}
export default {
  async fetch(req) {
    const url = new URL(req.url);
    if (req.method !== "GET" && req.method !== "HEAD") return new Response("Method not allowed", { status: 405 });
    let p = decodeURIComponent(url.pathname);
    let f = FILES[p];
    if (!f && p.endsWith("/")) { p += "index.html"; f = FILES[p]; }
    // SPA fallback: unknown paths without a file extension get index.html
    if (!f && !/\\.[a-z0-9]+$/i.test(p)) { p = "/index.html"; f = FILES[p]; }
    if (!f) return new Response("Not found", { status: 404, headers: SECURITY });
    const h = new Headers(SECURITY);
    h.set("Content-Type", f.t);
    h.set("Cache-Control", p.startsWith("/static/") ? "public, max-age=31536000, immutable" : "no-cache");
    return new Response(req.method === "HEAD" ? null : body(p, f), { headers: h });
  },
};
`;
const out = path.join(here, ".embedded", app);
mkdirSync(out, { recursive: true });
writeFileSync(path.join(out, "worker.js"), worker);
console.log(`${NAMES[app]}: ${Object.keys(files).length} files, ${(worker.length / 1024).toFixed(0)} KB script`);
if (process.argv.includes("--dry-run")) process.exit(0);

const wrangler = path.join(here, "..", "api", "node_modules", ".bin", process.platform === "win32" ? "wrangler.cmd" : "wrangler");
execFileSync(wrangler, ["deploy", path.join(out, "worker.js"), "--name", NAMES[app], "--compatibility-date", "2026-11-01", "--no-bundle"],
  { cwd: out, stdio: "inherit", shell: process.platform === "win32" });
